/* Host-only generator extracted from the HW1-derived Rubik model.
 * cc -O2 -std=c99 tools/gen_rubik_moves.c -o build/gen_rubik_moves
 * ./build/gen_rubik_moves > src/rubik/moves_data.h
 */
#include <stdint.h>
#include <stdio.h>

enum {
    CUBIES = 7,
    PERMUTATIONS = 5040,
    ORIENTATIONS = 729,
    STATES = PERMUTATIONS * ORIENTATIONS,
    MOVES = 9
};

typedef struct {
    uint8_t p[CUBIES], o[CUBIES];
} state_t;

static const uint8_t source[3][7] = {
    {1, 4, 2, 0, 3, 5, 6},
    {0, 1, 2, 4, 5, 6, 3},
    {0, 2, 5, 3, 1, 4, 6},
};

static const uint8_t twist[3][7] = {
    {1, 2, 0, 2, 1, 0, 0},
    {0, 0, 0, 1, 2, 1, 2},
    {0, 0, 0, 0, 0, 0, 0},
};

static state_t quarter_turn(state_t state, uint8_t face)
{
    state_t result;

    for (uint8_t i = 0; i < CUBIES; ++i) {
        uint8_t from = source[face][i];
        result.p[i] = state.p[from];
        unsigned value = state.o[from] + twist[face][i];
        if (value >= 3U)
            value -= 3U;
        result.o[i] = (uint8_t) value;
    }
    return result;
}

static void rank_components(const state_t *state,
                            uint16_t *permutation_rank,
                            uint16_t *orientation_rank)
{
    uint32_t p = 0, o = 0;

    for (uint8_t i = 0; i < CUBIES; ++i) {
        uint8_t smaller = 0;

        for (uint8_t j = (uint8_t) (i + 1U); j < CUBIES; ++j)
            if (state->p[j] < state->p[i])
                ++smaller;
        p = p * (CUBIES - i) + smaller;
    }

    for (uint8_t i = 0; i < 6; ++i)
        o = o * 3U + state->o[i];
    *permutation_rank = (uint16_t) p;
    *orientation_rank = (uint16_t) o;
}

static uint32_t rank_state(const state_t *state)
{
    uint16_t p, o;
    rank_components(state, &p, &o);
    return (uint32_t) p * ORIENTATIONS + o;
}

static void unrank_state(uint32_t rank, state_t *state)
{
    uint8_t available[CUBIES] = {0, 1, 2, 3, 4, 5, 6};
    uint32_t p = rank / ORIENTATIONS, o = rank % ORIENTATIONS, f = 720;
    uint8_t sum = 0;
    for (uint8_t i = 0; i < CUBIES; ++i) {
        uint8_t q = (uint8_t) (p / f);
        p %= f;
        state->p[i] = available[q];
        for (uint8_t j = q; j + 1U < (unsigned) (CUBIES - i); ++j)
            available[j] = available[j + 1U];
        if (i < 5)
            f /= 6U - i;
    }
    static const uint16_t weights[6] = {243, 81, 27, 9, 3, 1};
    for (uint8_t i = 0; i < 6; ++i) {
        uint32_t weight = weights[i], twice = weight << 1;
        uint8_t digit = 0;
        if (o >= twice) {
            o -= twice;
            digit = 2;
        } else if (o >= weight) {
            o -= weight;
            digit = 1;
        }
        state->o[i] = digit;
        sum = (uint8_t) (sum + digit);
        if (sum >= 3)
            sum = (uint8_t) (sum - 3);
    }
    state->o[6] = (uint8_t) (sum == 0 ? 0 : 3 - sum);
}

static uint16_t permutation[3][PERMUTATIONS];
static uint16_t orientation[3][ORIENTATIONS];

static void build_moves(void)
{
    state_t state;
    for (uint16_t p = 0; p < PERMUTATIONS; ++p) {
        unrank_state((uint32_t) p * ORIENTATIONS, &state);
        for (uint8_t face = 0; face < 3; ++face) {
            state_t next = quarter_turn(state, face);
            permutation[face][p] =
                (uint16_t) (rank_state(&next) / ORIENTATIONS);
        }
    }
    for (uint16_t o = 0; o < ORIENTATIONS; ++o) {
        unrank_state(o, &state);
        for (uint8_t face = 0; face < 3; ++face) {
            state_t next = quarter_turn(state, face);
            orientation[face][o] =
                (uint16_t) (rank_state(&next) % ORIENTATIONS);
        }
    }
}

/* The output preserves the solver's face-first quarter-turn layout. */
static void emit_table(const char *name, unsigned count, int is_orientation)
{
    printf("static const uint16_t %s[3][%u] = {\n", name, count);
    for (unsigned face = 0; face < 3; ++face) {
        const uint16_t *row =
            is_orientation ? orientation[face] : permutation[face];
        fputs("    {\n", stdout);
        for (unsigned i = 0; i < count; ++i) {
            if (i % 12 == 0)
                fputs("        ", stdout);
            printf("%u,", (unsigned) row[i]);
            if (i % 12 == 11 || i + 1 == count)
                putchar('\n');
            else
                putchar(' ');
        }
        fputs("    },\n", stdout);
    }
    fputs("};\n\n", stdout);
}

int main(void)
{
    build_moves();
    fputs(
        "/* Generated by tools/gen_rubik_moves.c on the host. */\n"
        "#ifndef RUBIK_MOVES_DATA_H\n#define RUBIK_MOVES_DATA_H\n"
        "#include <stdint.h>\n\n",
        stdout);
    emit_table("permutation", PERMUTATIONS, 0);
    emit_table("orientation", ORIENTATIONS, 1);
    fputs("#endif\n", stdout);
    return fflush(stdout) != 0 || ferror(stdout);
}
